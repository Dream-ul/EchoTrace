"""Persistence protocols shared by the runtime and concrete adapters."""

from __future__ import annotations

from contextlib import AbstractContextManager
from datetime import datetime
from typing import Any, Protocol, Self

from echotrace.domain.models import InvestigationRun


class InvestigationRepositoryPort(Protocol):
    def save(self, run: InvestigationRun, *, expected_state_version: int | None = None) -> InvestigationRun: ...

    def get(self, run_id: str) -> InvestigationRun | None: ...

    def list(self, *, limit: int | None = None) -> list[InvestigationRun]: ...

    def events(self, run_id: str, *, after_seq: int = 0) -> list[dict[str, Any]]: ...

    def append_event(self, *, run_id: str, event_type: str, actor_type: str, payload: dict[str, Any] | None = None, idempotency_key: str | None = None) -> int: ...


class CheckpointPort(Protocol):
    def append(self, run: InvestigationRun, *, state: dict[str, Any] | None = None) -> str: ...

    def latest(self, run_id: str) -> dict[str, Any] | None: ...


class OutboxPort(Protocol):
    def enqueue(
        self,
        *,
        aggregate_type: str,
        aggregate_id: str,
        event_type: str,
        payload: dict[str, Any],
        dedup_key: str,
        available_at: datetime | None = None,
    ) -> str: ...

    def claim(self, *, owner: str, limit: int = 50, lease_seconds: int = 60, now: datetime | None = None) -> list[dict[str, Any]]: ...
    def mark_published(self, outbox_id: str, *, owner: str, message_id: str) -> bool: ...
    def mark_failed(self, outbox_id: str, *, owner: str, error: str, dead: bool = False) -> bool: ...
    def has_unpublished_task(self, task_id: str) -> bool: ...


class TaskRepositoryPort(Protocol):
    def add_plan(self, *, run_id: str, objective: str, allowed_agents: list[str], allowed_capabilities: list[str], budget: dict[str, Any], stop_conditions: list[str], parent_plan_id: str | None = None, activate: bool = True, plan_id: str | None = None, plan_version: int | None = None, definition: dict[str, Any] | None = None) -> str: ...

    def add_task(self, *, run_id: str, plan_id: str, agent: str, stage: str, question: str, capability: str, idempotency_key: str, dependencies: list[str] | None = None, priority: int = 0, budget: dict[str, Any] | None = None, task_id: str | None = None, node_id: str | None = None, slot_id: str | None = None, node_revision: int | None = None, review_id: str | None = None, input_refs: list[str] | None = None, input_data: dict[str, Any] | None = None) -> str: ...

    def start_attempt(self, *, task_id: str, worker_id: str | None = None, expected_state_version: int | None = None, lease_seconds: int = 60) -> dict[str, Any]: ...

    def refresh_failed_task_budget(self, task_id: str, *, budget: dict[str, Any]) -> dict[str, Any]: ...

    def heartbeat_attempt(self, *, attempt_id: str, worker_id: str | None = None, lease_seconds: int = 60) -> bool: ...

    def finish_attempt(self, *, attempt_id: str, status: str, error_code: str | None = None, error_summary: str | None = None, output_refs: list[str] | None = None, worker_id: str | None = None) -> bool: ...

    def defer_attempt(self, *, attempt_id: str, worker_id: str | None = None, error_code: str = "run_paused", error_summary: str | None = None) -> bool: ...

    def get_attempts(self, task_id: str) -> list[dict[str, Any]]: ...

    def get_attempt(self, attempt_id: str) -> dict[str, Any] | None: ...

    def get_task(self, task_id: str) -> dict[str, Any] | None: ...
    def list_report_tasks(self, run_id: str) -> list[dict[str, Any]]: ...
    def get_node_plan(self, run_id: str) -> dict[str, Any] | None: ...
    def recover_expired(self, *, limit: int = 100, now: datetime | None = None) -> list[dict[str, Any]]: ...
    def list_pending(self, *, limit: int = 100) -> list[dict[str, Any]]: ...


class AuditRepositoryPort(Protocol):
    def register_skill(self, *, skill_name: str, description: str, content_hash: str, package_path: str) -> str: ...

    def register_provider(self, *, provider_name: str, provider_version: str, manifest_hash: str, capabilities: list[str]) -> str: ...

    def activate_skill(self, *, run_id: str, task_id: str, agent: str, skill_definition_id: str, step_no: int, reason_summary: str) -> str: ...

    def record_tool_call(self, **kwargs: Any) -> str: ...


class TraceNodeRepositoryPort(Protocol):
    def list_nodes(self, run_id: str) -> list[dict[str, Any]]: ...

    def begin_research(self, node_id: str, revision_no: int) -> bool: ...

    def save_revision(self, revision: Any) -> str: ...

    def save_review(self, review: Any) -> str: ...

    def get_review(self, node_id: str, revision_no: int | None = None) -> dict[str, Any] | None: ...

    def get_revision(self, node_id: str, revision_no: int | None = None) -> dict[str, Any] | None: ...

    def freeze_node(self, node_id: str) -> dict[str, Any]: ...

    def update_frozen_conclusion_ir(self, node_id: str, revision_no: int, conclusion_ir: Any) -> str: ...


class UnitOfWork(AbstractContextManager[Self], Protocol):
    runs: InvestigationRepositoryPort
    checkpoints: CheckpointPort
    outbox: OutboxPort
    tasks: TaskRepositoryPort
    audit: AuditRepositoryPort
    trace_nodes: TraceNodeRepositoryPort

    def commit(self) -> None: ...

    def rollback(self) -> None: ...
